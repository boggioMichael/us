//! Games Syrup can name before it has ever seen them.
//!
//! Only public, stable facts: titles, executable names, genres, Steam app
//! ids, where the game's wiki's MediaWiki API lives. The catalog is a head
//! start, never a requirement: any other game is recognised as "a new game"
//! and learned from scratch.

use syrup_core::Hat;

#[derive(Debug, Clone, Copy)]
pub struct CatalogEntry {
    pub id: &'static str,
    pub title: &'static str,
    pub aliases: &'static [&'static str],
    /// Executable file names, any case, `.exe` optional.
    pub executables: &'static [&'static str],
    pub genres: &'static [&'static str],
    pub steam_app: Option<u32>,
    /// The MediaWiki `api.php` of the game's community wiki, when known.
    pub wiki_api: Option<&'static str>,
    /// The English Wikipedia article title.
    pub wikipedia: Option<&'static str>,
    /// A hat that suits the game better than its genres would pick.
    pub hat: Option<Hat>,
}

const fn game(
    id: &'static str,
    title: &'static str,
    aliases: &'static [&'static str],
    executables: &'static [&'static str],
    genres: &'static [&'static str],
    steam_app: Option<u32>,
    wiki_api: Option<&'static str>,
    wikipedia: Option<&'static str>,
) -> CatalogEntry {
    CatalogEntry { id, title, aliases, executables, genres, steam_app, wiki_api, wikipedia, hat: None }
}

